async (page) => {
  await page.goto('http://127.0.0.1:58882/converter');
  await page.locator('.conversion-options').evaluate(el => el.open = true);
  await page.locator('[name=roundtrip]').check();
  const nested = JSON.stringify({id:'00123',nested:{items:[1,{note:'世界'}]},nil:null});
  await page.locator('#convert-input').fill(nested);
  await page.getByRole('button',{name:'Convert data →',exact:true}).click();
  await page.locator('.conversion-report').filter({hasText:'normalized values and types match'}).waitFor();
  await page.locator('#input-tree summary').first().click();
  await page.locator('#input-tree .tree-node summary').first().click();
  if (!(await page.locator('#input-tree').textContent()).includes('00123')) throw Error('Input tree missing exact values');
  await page.locator('.tree-preview').filter({hasText:'Explore output structure'}).locator('summary').first().click();
  await page.locator('#target-format').selectOption('csv');
  await page.getByRole('button',{name:'Convert data →',exact:true}).click();
  await page.locator('.conversion-report').filter({hasText:'Round-trip differences'}).waitFor();
  const csv = 'id,price,meta'+String.fromCharCode(10)+'00123,2.50,"{""a"":[1,null]}"'+String.fromCharCode(10);
  await page.locator('#convert-input').fill(csv);
  await page.locator('#source-format').selectOption('csv');
  await page.locator('#target-format').selectOption('json');
  await page.locator('[name=column_types]').fill('id=text'+String.fromCharCode(10)+'price=number'+String.fromCharCode(10)+'meta=json');
  await page.getByRole('button',{name:'Convert data →',exact:true}).click();
  await page.locator('[data-output-status]').filter({hasText:'JSON ready'}).waitFor({timeout:120000});
  const value=JSON.parse(await page.locator('#convert-output').inputValue());
  if(value[0].id!=='00123'||value[0].price!==2.5||value[0].meta.a[1]!==null) throw Error('CSV column controls failed');
  await page.locator('[name=column_types]').fill('');
  await page.locator('#source-format').selectOption('json');
  await page.locator('#convert-input').fill('{'+String.fromCharCode(10)+'"x": ]}');
  await page.getByRole('button',{name:'Convert data →',exact:true}).click();
  await page.locator('#feedback').filter({hasText:'Line 2'}).waitFor();
  const uploaded=JSON.stringify({id:'00123',nested:{text:'Uploaded contents visible'}});
  await page.locator('#converter-file').setInputFiles({name:'inspection.json',mimeType:'application/json',buffer:Buffer.from(uploaded)});
  await page.waitForFunction(text=>document.querySelector('#convert-input').value===text,uploaded);
  await page.locator('#target-format').selectOption('yaml');
  await page.getByRole('button',{name:'Convert data →',exact:true}).click();
  await page.locator('[data-output-status]').filter({hasText:'YAML ready'}).waitFor({timeout:120000});
  await page.locator('.conversion-report').filter({hasText:'normalized values and types match'}).waitFor();
  await page.waitForFunction(()=>!document.querySelector('#feedback').textContent.trim());
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'output/playwright/converter-inspection-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)) throw Error('Mobile overflow');
  await page.screenshot({path:'output/playwright/converter-inspection-mobile.png',fullPage:true});
}
