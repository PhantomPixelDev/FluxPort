// Playwright CLI callback; no existing collections are modified.
async (page) => {
  const base = new URL(page.url()).origin;
  await page.goto(`${base}/converter`);
  await page.locator('.conversion-options > summary').click();
  const newline=String.fromCharCode(10); const nested=JSON.stringify({data:{children:[{note:"  first"+newline+"second"+newline,amount:"EXACT_AMOUNT",id:"EXACT_ID",html:"<b>&</b>"}],empty:[],missing:null}}).replace('"EXACT_AMOUNT"',"1.234567890123456789").replace('"EXACT_ID"',"184467440737095516160");
  const convert = async (input, from, to) => {
    await page.locator('#source-format').selectOption(from);
    await page.locator('#target-format').selectOption(to);
    await page.locator('#convert-input').fill(input);
    const response = page.waitForResponse(r => r.url().endsWith('/converter') && r.request().method() === 'POST');
    await page.getByRole('button', {name: 'Convert data →', exact: true}).click();
    const r = await response;
    if (r.status() !== 200) throw Error(`Conversion ${from} → ${to} failed: ${r.status()}`);
    await page.locator('[data-output-status]').filter({hasText: 'ready'}).waitFor({timeout:120000});
    return await page.locator('#convert-output').inputValue();
  };
  const yaml = await convert(nested, 'json', 'yaml');
  const json = await convert(yaml, 'yaml', 'json');
  if (!json.includes('1.234567890123456789') || !json.includes('184467440737095516160')) throw Error('Numeric precision changed');
  const data = JSON.parse(json).data;
  if (data.children[0].note !== '  first\nsecond\n' || data.children[0].html !== '<b>&</b>' || data.missing !== null || data.empty.length) throw Error('Nested values changed');
  const dates = JSON.parse(await convert('date: 2024-01-01', 'yaml', 'json'));
  if (dates.date !== '2024-01-01') throw Error('Date changed');
  await page.locator('[name=infer_types]').check();
  const csv = JSON.parse(await convert('id;price;enabled;empty;missing\n00123;2.50;true;;null\n', 'csv', 'json'))[0];
  if (csv.id !== '00123' || csv.price !== 2.5 || csv.enabled !== true || csv.empty !== '' || csv.missing !== null) throw Error('CSV inference changed IDs or types');
  await page.locator('[name=spreadsheet_safe]').check();
  const safe = await convert('{"formula":"=SUM(1)","nested":{"x":[1,2]}}', 'json', 'csv');
  if (!safe.includes("'=SUM(1)")) throw Error('Formula protection missing');
  await page.locator('.conversion-notes').filter({hasText: 'flat text format'}).waitFor();
  await page.locator('#source-format').selectOption('json');
  await page.locator('#target-format').selectOption('yaml');
  await page.locator('#convert-input').fill('{"x":1,"x":2}');
  await page.getByRole('button', {name: 'Convert data →', exact: true}).click();
  await page.locator('#feedback').filter({hasText: 'duplicate JSON key'}).waitFor();
  if (await page.locator('#convert-output').inputValue() !== safe) throw Error('Failed conversion destroyed previous result');
  await page.locator('[data-output-status]').filter({hasText: 'conversion failed'}).waitFor();
  const xml = JSON.parse(await convert('<root>hello <child>c1</child> world</root>', 'xml', 'json')).root['#content'];
  if (xml[0]['#text'] !== 'hello ' || xml[1].child !== 'c1' || xml[2]['#text'] !== ' world') throw Error('XML mixed content order changed');
  if ((await page.locator('#feedback').textContent()).trim()) throw Error('Old error feedback remains after success');
  const header = await convert('id;name\n', 'csv', 'csv');
  if (header !== 'id,name\n') throw Error('Header-only CSV lost columns');
  const empty = await convert('[]', 'json', 'ndjson');
  if (empty !== '' || await page.locator('#convert-output').getAttribute('data-ready') !== 'true') throw Error('Empty NDJSON result not ready');
  const download = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Download ↓', exact: true}).click();
  const file = await download;
  if (file.suggestedFilename() !== 'converted.ndjson') throw Error('Wrong output filename');
  await file.saveAs('output/playwright/empty.ndjson');
  await page.locator('#target-format').selectOption('yaml');
  await page.locator('#converter-file').setInputFiles({name: 'nested.json', mimeType: 'application/json', buffer: Buffer.from(nested)});
  await page.getByRole('button', {name: 'Convert data →', exact: true}).click();
  await page.locator('[data-output-status]').filter({hasText: 'YAML ready'}).waitFor({timeout:120000});
  await page.setViewportSize({width: 1440, height: 1000});
  await page.screenshot({path: 'output/playwright/converter-fidelity-desktop.png', fullPage: true});
  await page.setViewportSize({width: 390, height: 844});
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw Error('Mobile converter overflow');
  await page.screenshot({path: 'output/playwright/converter-fidelity-mobile.png', fullPage: true});
}
